import assert from 'node:assert/strict';
import {test} from 'node:test';
import {request} from 'node:http';
import {mkdtemp, readFile, readdir, rm, writeFile, symlink} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {startServer} from '../scripts/serve.mjs';
import {renderIcon} from '../scripts/icons.mjs';

const svgSource = new URL('../favicon.svg', import.meta.url);

test('preview serves only public files on loopback and rejects private or encoded paths', async () => {
  const {server, url} = await startServer();
  const get = (path, method = 'GET') => new Promise((resolve, reject) => {
    const req = request(url, {path, method}, response => {
      const chunks = [];
      response.on('data', chunk => chunks.push(chunk));
      response.on('end', () => resolve({status: response.statusCode, headers: response.headers, body: Buffer.concat(chunks)}));
    });
    req.on('error', reject).end();
  });
  try {
    assert.equal(server.address().address, '127.0.0.1');
    const page = await get('/');
    assert.equal(page.status, 200);
    assert.match(page.headers['content-type'], /^text\/html/);
    assert.ok(page.body.includes('<!doctype html>'));
    assert.equal((await get('/app.js?v=1')).headers['content-type'], 'text/javascript; charset=utf-8');
    const head = await get('/README.md', 'HEAD');
    assert.equal(head.status, 200);
    assert.equal(head.body.length, 0);
    const svg = await readFile(svgSource);
    for (const [name, size] of [['favicon.png', 64], ['apple-touch-icon.png', 180]]) {
      const image = await get(`/${name}?v=1`);
      assert.equal(image.status, 200);
      assert.equal(image.headers['content-type'], 'image/png');
      assert.equal(image.headers['x-content-type-options'], 'nosniff');
      assert.deepEqual(image.body, renderIcon(svg, size), 'Preview returns the generated bytes unchanged');
      const imageHead = await get(`/${name}`, 'HEAD');
      assert.equal(imageHead.body.length, 0);
      assert.equal(Number(imageHead.headers['content-length']), image.body.length);
      assert.equal(imageHead.headers['content-type'], 'image/png');
    }
    for (const path of ['/.git/config', '/DEVELOPMENT.md', '/tests/', '/../README.md', '/%2e%2e/README.md', '/%2fREADME.md', '//README.md', '/scripts/serve.mjs', '/scripts/icons.mjs', '/markdown.js', '/favicon.svg', '/favicon%2epng', '/%2e%2e/favicon.png', '/node_modules/@resvg/resvg-js/index.js']) {
      assert.equal((await get(path)).status, 404, path);
    }
    assert.equal((await get('/', 'POST')).status, 405);
  } finally { await new Promise(resolve => server.close(resolve)); }
});

test('preview renders current content without writing generated files into the source tree', async t => {
  const root = await mkdtemp(join(tmpdir(), 'site-preview-'));
  t.after(() => rm(root, {recursive: true, force: true}));
  const template = await readFile(new URL('../index.html', import.meta.url), 'utf8');
  await writeFile(join(root, 'index.html'), template);
  await writeFile(join(root, 'README.md'), 'First version.\n');
  const svg = await readFile(svgSource, 'utf8');
  await writeFile(join(root, 'favicon.svg'), svg);
  const {server, url} = await startServer({root});
  try {
    const first = await (await fetch(url)).text();
    assert.ok(first.includes('<p>First version.</p>'));
    await writeFile(join(root, 'README.md'), 'Second version.\n');
    const second = await (await fetch(url)).text();
    assert.ok(second.includes('<p>Second version.</p>'));
    assert.ok(!second.includes('First version.'));
    const before = await Promise.all(['favicon.png', 'apple-touch-icon.png'].map(async name =>
      Buffer.from(await (await fetch(url + name)).arrayBuffer())));
    const revisedSvg = svg.replace('#9dc9e8', '#ffffff');
    assert.notEqual(svg, revisedSvg);
    await writeFile(join(root, 'favicon.svg'), revisedSvg);
    for (const [index, name] of ['favicon.png', 'apple-touch-icon.png'].entries()) {
      const image = await fetch(url + name);
      assert.equal(image.status, 200);
      assert.notDeepEqual(Buffer.from(await image.arrayBuffer()), before[index], 'Preview reflects SVG edits on the next request');
    }
    assert.equal(await readFile(join(root, 'index.html'), 'utf8'), template);
    assert.equal(await readFile(join(root, 'favicon.svg'), 'utf8'), revisedSvg);
    assert.deepEqual((await readdir(root)).sort(), ['README.md', 'favicon.svg', 'index.html']);
  } finally { await new Promise(resolve => server.close(resolve)); }
});

test('preview rejects missing, invalid, and symlinked icon sources without exposing other files', async t => {
  for (const kind of ['missing', 'invalid', 'symlink']) {
    const root = await mkdtemp(join(tmpdir(), 'site-icon-preview-'));
    t.after(() => rm(root, {recursive: true, force: true}));
    if (kind === 'invalid') await writeFile(join(root, 'favicon.svg'), 'not an SVG');
    if (kind === 'symlink') await symlink(svgSource, join(root, 'favicon.svg'));
    const {server, url} = await startServer({root});
    try {
      for (const name of ['favicon.png', 'apple-touch-icon.png']) {
        const response = await fetch(url + name);
        assert.equal(response.status, 404, `${kind}: ${name}`);
        assert.equal(await response.text(), '');
      }
    } finally { await new Promise(resolve => server.close(resolve)); }
  }
});
